// chunk.ts 纯函数回归测试（尾部裁剪 / markdown 分块 / token 估算）——索引管线里不依赖应用的文本层。
// 运行：node scripts/test-chunk.mjs（esbuild 现编译 src/main/chunk.ts 后执行）
import { build } from 'esbuild'
import { mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const outDir = path.join(root, '.zcode', 'tmp')
mkdirSync(outDir, { recursive: true })
const outFile = path.join(outDir, 'chunk.test.mjs')
await build({
  entryPoints: [path.join(root, 'src/main/chunk.ts')],
  outfile: outFile,
  bundle: true,
  format: 'esm',
  platform: 'node',
  logLevel: 'silent'
})
const { stripBackMatter, parseMdBlockPages, chunkMdBlocks, chunkPages, estimateTokens, splitSentences } = await import('file://' + outFile.replace(/\\/g, '/'))

let pass = 0
const fail = []
const eq = (name, got, want) => {
  const g = JSON.stringify(got)
  const w = JSON.stringify(want)
  if (g === w) pass++
  else fail.push(`${name}\n  got:  ${g.slice(0, 400)}\n  want: ${w.slice(0, 400)}`)
}
const body = (n, tag) => Array.from({ length: n }, (_, i) => `${tag} sentence number ${i} about thermal parameters and gate charge behaviour in power modules.`)
const join = (lines) => lines.join('\n')

// ---------- 尾部裁剪 ----------
// 首页脚注里的致谢（IEEE 双栏：排在左栏末尾，后面还有右栏和整篇正文）：不能照它裁
{
  const p1 = [...body(25, 'left'), 'Acknowledgment', 'The authors would like to thank the anonymous reviewers.', ...body(25, 'right')]
  const p2 = body(50, 'p2')
  const p3 = [...body(30, 'p3'), 'References', '[1] A. Author, "Title," Journal, vol. 1, pp. 1-2, 2020.']
  const out = stripBackMatter([join(p1), join(p2), join(p3)])
  eq('首页脚注致谢：首页右栏保留', out[0].includes('right sentence number 24') && out[0].includes('Acknowledgment'), true)
  eq('首页脚注致谢：中间页完整', out[1], join(p2))
  eq('首页脚注致谢：只裁掉末页的参考文献', out[2], join(body(30, 'p3')))
  eq('尾部裁剪：数组长度不变（页码语义）', out.length, 3)
}
// 首页脚注致谢、全文没有参考文献标题：一个字都不能少
{
  const pages = [[...body(25, 'left'), 'Acknowledgment', 'Thanks.', ...body(25, 'right')], body(50, 'p2'), body(50, 'p3')].map(join)
  eq('首页脚注致谢且无参考文献：全文保留', stripBackMatter(pages), pages)
}
// 真正的致谢章节（在末尾、到参考文献前内容很少）
{
  const pages = [body(40, 'p1'), body(40, 'p2'), body(40, 'p3'), body(40, 'p4'), body(40, 'p5'), [...body(10, 'p6'), 'ACKNOWLEDGMENT', 'This work was supported by the National Science Foundation.', 'REFERENCES', '[1] A. Author, "Title," 2020.', '[2] B. Author, "Title," 2021.']]
  const out = stripBackMatter(pages.map(join))
  eq('末尾的致谢章节：从致谢处裁掉', out[5], join(body(10, 'p6')))
  eq('末尾的致谢章节：前面的页不受影响', out.slice(0, 5), pages.slice(0, 5).map(join))
}
// 两页短文：致谢在第 2 页末尾、后面紧跟参考文献
{
  const out = stripBackMatter([join(body(40, 'p1')), join([...body(20, 'p2'), 'Acknowledgments', 'The authors thank X for helpful discussions.', 'References', '[1] A. Author, "Title," 2020.'])])
  eq('两页短文：只裁第 2 页致谢及其后', out[1], join(body(20, 'p2')))
}
// 整篇一页，致谢在末尾
eq('一页文档：裁掉末尾致谢', stripBackMatter([join([...body(30, 'p1'), 'Acknowledgments', 'Thanks.'])]), [join(body(30, 'p1'))])
// 作者简介在最后一页
eq('作者简介在末页：整页裁掉', stripBackMatter([join(body(40, 'p1')), join(body(40, 'p2')), join(['Biographies', 'Author One received the B.S. degree.', 'Author Two received the Ph.D. degree.'])])[2], '')
// 带章节编号的参考文献标题
eq('带编号的参考文献标题（IV. REFERENCES）', stripBackMatter([join([...body(20, 'p1'), 'IV. REFERENCES', '[1] A. Author, 2020.'])]), [join(body(20, 'p1'))])
// 没有尾部章节：原样返回同一份数组
{
  const pages = [join(body(20, 'p1')), join(body(20, 'p2'))]
  eq('没有尾部章节：原样返回', stripBackMatter(pages), pages)
}

// ---------- markdown 分块 ----------
// 标题必须整行是尾部章节名：「Reference Signal Generation」是正经小节，不能丢
{
  const jobs = chunkMdBlocks(parseMdBlockPages([{ page: 1, md: '## 1. Introduction\nThe introduction of the paper.\n## Reference Signal Generation\nThe reference signal is generated by a resolver.\n## A. Reference Frame Oriented Control\nControl is performed in the rotating frame.\n## References\n[1] Somebody, "Some Title," 2020.' }]))
  const text = jobs.map((j) => j.text).join('\n')
  eq('小节标题 Reference …：正文保留', /reference signal is generated by a resolver/.test(text) && /rotating frame/.test(text), true)
  eq('参考文献条目：不进索引', /\[1\] Somebody/.test(text), false)
  eq('小节标题 Reference …：章节号正确', jobs.map((j) => j.sectionNo).filter(Boolean), ['1', 'A'])
}
// 跨页段落的残尾（不足 40 token）后面紧跟标题：以前直接丢弃
{
  const jobs = chunkMdBlocks(parseMdBlockPages([{ page: 1, md: '## 1 Introduction\n' + body(4, 'intro').join(' ') }, { page: 2, md: 'tail words of a split paragraph.\n## 2 Method\n' + body(4, 'method').join(' ') }]))
  eq('跨页段落残尾：保留成块', jobs.some((j) => j.text === 'tail words of a split paragraph.'), true)
  eq('跨页段落残尾：页码是它所在的页', jobs.find((j) => j.text === 'tail words of a split paragraph.')?.page, 2)
}
// 整篇文本经过分块后一句不丢（去掉了空行与标题行）
{
  const paras = [...body(3, 'a'), ...body(3, 'b'), ...body(3, 'c')]
  const md = '## Intro\n' + paras.join('\n')
  const jobs = chunkMdBlocks(parseMdBlockPages([{ page: 1, md }, { page: 2, md: body(3, 'd').join('\n') }]))
  const all = jobs.map((j) => j.text).join('\n')
  eq('分块不丢句子', [...paras, ...body(3, 'd')].every((p) => all.includes(p)), true)
  // 库内 text 是干净原文：嵌入用的重叠 / 论点句只出现在 embedText
  eq('库内文本不含论点句前缀', jobs.some((j) => j.text.includes('本段论点')), false)
  eq('嵌入文本与库内文本一一对应', jobs.every((j) => j.embedText.includes(j.text)), true)
}
// 内置回退路径（按页分块）：页码从 1 起、顺序连续
{
  const jobs = chunkPages([body(6, 'p1').join('\n'), body(6, 'p2').join('\n')])
  eq('内置分块：页码', [...new Set(jobs.map((j) => j.page))], [1, 2])
  eq('内置分块：ord 连续', jobs.map((j) => j.ord), jobs.map((_, i) => i))
}

// ---------- token 估算 / 断句 ----------
eq('token 估算：拉丁约 4 字符一个', estimateTokens('a'.repeat(400)), 100)
eq('token 估算：CJK 每字一个', estimateTokens('功率器件'.repeat(25)), 100)
eq('断句：中英文句读', splitSentences('First one. Second one！第三句？'), ['First one.', 'Second one！', '第三句？'])

console.log(`chunk tests: ${pass} passed, ${fail.length} failed`)
if (fail.length) {
  console.error(fail.join('\n'))
  process.exit(1)
}
